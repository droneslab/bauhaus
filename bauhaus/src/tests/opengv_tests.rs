    // #[test]
    fn test_k() {
        let n_best_inliers_count = 23;
        let indices = 232;
        let selection_size = 2;
        let probability = 0.995;

        let w = (n_best_inliers_count as f64) / (indices as f64);
        let mut p_no_outliers = 1.0 - (num_traits::pow(w, selection_size) as f64);
        p_no_outliers = f64::max(f64::EPSILON, p_no_outliers); // Avoid division by -Inf
        p_no_outliers = f64::min(1.0 - f64::EPSILON, p_no_outliers); // Avoid division by 0.
        let k = (1.0 - probability as f64).ln() / (p_no_outliers).ln();

        assert_eq!(w, 0.099137931034482762);
        assert_eq!(k, 536.43274492219393);
    }


    #[test]
    fn test_two_pt() {
        // tests two_pt through function compute_model_coefficients
        let adapter = get_central_relative_adapter();
        let mut problem = TranslationOnlySacProblem::new(adapter, false);

        let indices1 = 77;
        let indices2 = 193;
        let threshold = 0.000001;

        let mut model_coefficients = TransformationT::default();
        // let res = two_pt(&adapter, true, indices1, indices2);
        problem.compute_model_coefficients(&vec![indices1, indices2], &mut model_coefficients);
        let translation_result = model_coefficients.translation;
        assert!(
            (translation_result - Vector3::new(-0.0023119442899574741,  -0.90299672699084821, -0.42964120607480788).abs())
            < Vector3::new(0.000001, 0.000001, 0.000001)
        );

        let inliers = problem.count_within_distance(&model_coefficients, threshold);

        assert_eq!(inliers, 23);
    }

